/**
 * Network-held HBAR and the wrapped-HBAR contract, as classification for an
 * HBAR project (written by `npm run onboard -- --chain hedera --write`).
 *
 * Owner decisions 2026-11-08: unreleased and Council accounts are Team/Treasury,
 * the staking reward pool 0.0.800 and fee account 0.0.98 are treasury, WHBAR is
 * DEX/wrapped with no look-through. The unreleased ranges were corrected by the
 * 2026-11-10 dry run: 0.0.900-1000 is circulating; without it the listed ranges
 * reconcile to total minus released supply to the tinybar at the same snapshot.
 */
export const HEDERA_UNRELEASED_RANGES = Object.freeze([
  { from: 2, to: 2, name: "Hedera network treasury 0.0.2 (unreleased)" },
  { from: 42, to: 42, name: "Hedera unreleased supply 0.0.42" },
  { from: 44, to: 71, name: "Hedera unreleased supply (0.0.44-71)" },
  { from: 73, to: 87, name: "Hedera unreleased supply (0.0.73-87)" },
  { from: 99, to: 100, name: "Hedera unreleased supply (0.0.99-100)" },
  { from: 200, to: 349, name: "Hedera unreleased supply (0.0.200-349)" },
  { from: 400, to: 750, name: "Hedera Council treasury (0.0.400-750, unreleased)" },
]);

/**
 * Network accounts that pay fees and rewards. 0.0.801 is the node reward account
 * (HIP-406), the same kind of pool as 0.0.800, so it is treated alike. 0.0.802
 * (about 859 HBAR on 2026-11-11) is unidentified and stays circulating.
 */
export const HEDERA_NETWORK_ACCOUNTS = Object.freeze([
  { num: 98, name: "Hedera network fee account 0.0.98" },
  { num: 800, name: "Hedera staking reward account 0.0.800 (HIP-406)" },
  { num: 801, name: "Hedera node reward account 0.0.801 (HIP-406)" },
]);

export const WHBAR_CONTRACT = "0.0.1456985";

/** contracts{} entries for the hedera chain: WHBAR holds the HBAR behind wrapped HBAR in DEX pools. */
export const hederaChainContracts = () => ({
  whbar: {
    address: WHBAR_CONTRACT,
    role: "dex",
    $comment: "WHBAR contract (token 0.0.1456986, 8 decimals): its HBAR backs wrapped HBAR in SaucerSwap and other DEX pools. Owner decision 2026-11-08: DEX/wrapped, no look-through to WHBAR holders.",
  },
});

/** Every treasury account id (`0.0.N`), in order: each id in the ranges, then the network accounts. */
export function hederaTreasuryAccounts() {
  const out = [];
  for (const r of HEDERA_UNRELEASED_RANGES) for (let n = r.from; n <= r.to; n += 1) out.push({ address: `0.0.${n}`, name: r.name });
  for (const a of HEDERA_NETWORK_ACCOUNTS) out.push({ address: `0.0.${a.num}`, name: a.name });
  return out;
}

/** exclusions.json content: every id listed, so an account that is empty today still counts as treasury if it is funded. */
export function hederaTreasuryExclusions() {
  const accounts = hederaTreasuryAccounts();
  const note =
    "Owner decisions 2026-11-08 (unreleased and Council accounts, 0.0.800 and 0.0.98 are Team/Treasury; Treasury and Team are one bucket), ranges corrected 2026-11-10 (0.0.900-1000 is circulating). Generated by scripts/lib/hedera/treasury.js.";
  return {
    $comment: "HBAR network treasury, generated by scripts/lib/hedera/treasury.js. Regenerate rather than hand-edit.",
    addresses: accounts.map((a) => a.address),
    labels: Object.fromEntries(accounts.map((a) => [a.address, { category: "treasury", name: a.name, evidenceTier: "owner-supplied", confidence: "confirmed", note }])),
  };
}
